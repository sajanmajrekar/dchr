            $(function () {
                function updateServiceChoiceLabel() {
                    var maxServices = 3;
                    var selectedCount = $('input[name="services[]"]:checked').length;
                    var $count = $('#service-count');

                    if (selectedCount > 0) {
                        $count.text(selectedCount + ' service' + (selectedCount === 1 ? '' : 's') + ' selected').addClass('is-visible');
                    } else {
                        $count.text('Choose up to 3 services').removeClass('is-visible');
                    }

                    $('input[name="services[]"]').each(function () {
                        var shouldDisable = selectedCount >= maxServices && !this.checked;
                        $(this).prop('disabled', shouldDisable).closest('.service-option').toggleClass('is-disabled', shouldDisable);
                    });
                }

                function showThankYouPopup(message) {
                    $('#thankyou-message').text(message);
                    $('#thankyou-modal').addClass('is-visible');
                }

                $('.thankyou-close, #thankyou-modal').on('click', function (event) {
                    if (event.target === this) {
                        $('#thankyou-modal').removeClass('is-visible');
                    }
                });

                $('input[name="services[]"]').on('change', updateServiceChoiceLabel);
                updateServiceChoiceLabel();

                $('#partner-form').validate({
                    errorClass: 'help-block animation-pullUp',
                    errorElement: 'div',
                    errorPlacement: function (error, element) {
                        element.parents('.form-group > div').append(error);
                    },
                    highlight: function (element) {
                        $(element).closest('.form-group').removeClass('has-success has-error').addClass('has-error');
                    },
                    success: function (element) {
                        element.closest('.form-group').removeClass('has-success has-error');
                        element.closest('.help-block').remove();
                    },
                    submitHandler: function (form) {
                        var selectedCount = $('input[name="services[]"]:checked').length;

                        if (selectedCount === 0) {
                            alert('Please select at least one service.');
                            return false;
                        }

                        if (selectedCount > 3) {
                            alert('Please select maximum 3 services.');
                            return false;
                        }

                        $.ajax({
                            url: 'https://digichefs.in/newhr/php_actions/createpartnerweb.php',
                            type: 'POST',
                            data: $(form).serialize(),
                            dataType: 'json',
                            success: function (response) {
                                if (response.success) {
                                    form.reset();
                                    $('input[name="services[]"]').prop('checked', false).prop('disabled', false).closest('.service-option').removeClass('is-disabled');
                                    updateServiceChoiceLabel();
                                    showThankYouPopup(response.messages || 'Thank you! Your partner details have been submitted successfully.');
                                } else {
                                    alert(response.messages || 'Something went wrong while submitting the form. Please try again.');
                                }
                            },
                            error: function () {
                                alert('Something went wrong while submitting the form. Please try again.');
                            }
                        });
                        return false;
                    }
                });
            });
        </script>
